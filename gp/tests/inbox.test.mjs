import test from 'node:test'
import assert from 'node:assert/strict'
import { register } from 'node:module'

// lib/inboxWorker.ts imports './inboxCore' without an extension (fine for the bundler and tsc,
// not for bare Node), so a tiny resolve hook retries a relative miss as '.ts'.
register('data:text/javascript,' + encodeURIComponent(`
export async function resolve(spec, ctx, next) {
  try { return await next(spec, ctx) } catch (e) {
    if (e && e.code === 'ERR_MODULE_NOT_FOUND' && /^\\.{1,2}\\//.test(spec) && !/\\.[cm]?[jt]s$/.test(spec)) return next(spec + '.ts', ctx)
    throw e
  }
}`), import.meta.url)

const {
  normalizeAddress, normalizeMessageId, messageIdsFrom, ticketNoFromSubject, cleanSubject, replySubject,
  isAutoGenerated, htmlToPlainText, bodyText, validatePayload, quoteForReply,
} = await import('../lib/inboxCore.ts')
const { parseInboundMime, unreadablePayload } = await import('../lib/inboxWorker.ts')

const enc = (s) => new TextEncoder().encode(s)

test('addresses and message ids are normalised', () => {
  assert.equal(normalizeAddress('  Jane@Example.COM '), 'jane@example.com')
  assert.equal(normalizeAddress('<jane@example.com>'), 'jane@example.com')
  assert.equal(normalizeAddress('not an address'), null)
  assert.equal(normalizeAddress('a@b'), null)
  assert.equal(normalizeAddress(42), null)
  assert.equal(normalizeMessageId('<ABC.123@Mail.Example.com>'), 'abc.123@mail.example.com')
  assert.equal(normalizeMessageId(''), null)
})

test('In-Reply-To and References become one de-duplicated id list', () => {
  assert.deepEqual(
    messageIdsFrom('<a@x>', '<b@x> <a@x>\n <c@x>'),
    ['a@x', 'b@x', 'c@x'],
  )
  assert.deepEqual(messageIdsFrom(null, undefined), [])
})

test('the [GP-n] ticket reference is read from, and put on, subjects', () => {
  assert.equal(ticketNoFromSubject('Re: Help [GP-1042]'), 1042)
  assert.equal(ticketNoFromSubject('re: help [gp-7]'), 7)
  assert.equal(ticketNoFromSubject('GP-1042 without brackets'), null)
  assert.equal(ticketNoFromSubject('[GP-0]'), null)
  assert.equal(ticketNoFromSubject('[GP-99999999999999999999]'), null)
  assert.equal(replySubject('Re: RE: Help me [GP-12]', 12), 'Re: Help me [GP-12]')
  assert.equal(cleanSubject('Fwd: Re: AW: hello\r\nBcc: evil@x'), 'hello Bcc: evil@x')
  assert.equal(cleanSubject('   '), '(no subject)')
  assert.equal(cleanSubject(null), '(no subject)')
})

test('machine-written mail is recognised and never treated as a person', () => {
  assert.equal(isAutoGenerated({ 'auto-submitted': 'auto-replied' }, 'a@b.co'), true)
  assert.equal(isAutoGenerated({ 'auto-submitted': 'no' }, 'a@b.co'), false)
  assert.equal(isAutoGenerated({ precedence: 'bulk' }, 'a@b.co'), true)
  assert.equal(isAutoGenerated({ 'list-id': '<news.example.com>' }, 'a@b.co'), true)
  assert.equal(isAutoGenerated({ 'x-auto-response-suppress': 'All' }, 'a@b.co'), true)
  assert.equal(isAutoGenerated({ 'content-type': 'multipart/report; report-type=delivery-status' }, 'a@b.co'), true)
  assert.equal(isAutoGenerated({}, 'mailer-daemon@googlemail.com'), true)
  assert.equal(isAutoGenerated({}, 'jane@example.com'), false)
})

test('an HTML-only message still reads as text, and nothing is ever rendered as HTML', () => {
  const t = htmlToPlainText('<style>p{}</style><p>Hello <b>there</b></p><a href="https://x.co/a">link</a><script>alert(1)</script>')
  assert.ok(t.includes('Hello there'))
  assert.ok(t.includes('link (https://x.co/a)'))
  assert.ok(!t.includes('alert'))
  assert.ok(!t.includes('<'))
  assert.equal(bodyText({ text: '  ', html: '<p>Hi</p>' }), 'Hi')
  assert.equal(bodyText({ text: 'plain', html: '<p>Hi</p>' }), 'plain')
  assert.equal(bodyText({ text: 'a\u0000b', html: null }), 'ab')
})

test('quoting a reply prefixes every line', () => {
  assert.equal(quoteForReply('one\ntwo', 'Jane', 'Mon'), 'On Mon, Jane wrote:\n> one\n> two')
})

test('a payload is validated and clamped before it reaches the database', () => {
  assert.equal(validatePayload(null).ok, false)
  assert.equal(validatePayload({}).ok, false)
  const ok = validatePayload({
    envelope_to: 'Support@Globproxy.com', envelope_from: 'jane@example.com',
    message_id: '<m1@x>', from: { address: 'Jane@Example.com', name: 'Jane\r\nBcc: x' },
    to: ['support@globproxy.com', 'junk'], subject: 'Hi', text: 'Body',
    headers: { 'Auto-Submitted': 'no', n: 5 }, attachments: [{ filename: 'a.pdf', mime_type: 'application/pdf', size: '12' }],
  })
  assert.equal(ok.ok, true)
  assert.equal(ok.value.envelope_to, 'support@globproxy.com')
  assert.equal(ok.value.message_id, 'm1@x')
  assert.equal(ok.value.from.address, 'jane@example.com')
  assert.ok(!/[\r\n]/.test(ok.value.from.name))
  assert.deepEqual(ok.value.to, ['support@globproxy.com'])
  assert.deepEqual(ok.value.headers, { 'auto-submitted': 'no' })
  assert.equal(ok.value.attachments[0].size, 12)
})

test('a real multipart message is parsed into the payload the store expects', async () => {
  const mime = [
    'From: "Jane Doe" <Jane@Example.com>',
    'To: GlobProxy Support <support@globproxy.com>',
    'Subject: Re: My proxy stopped [GP-42]',
    'Message-ID: <CAF123@mail.example.com>',
    'In-Reply-To: <reply-1@globproxy.com>',
    'References: <first@mail.example.com> <reply-1@globproxy.com>',
    'Date: Mon, 26 Oct 2026 07:00:00 +0300',
    'MIME-Version: 1.0',
    'Content-Type: multipart/mixed; boundary="b1"',
    '',
    '--b1',
    'Content-Type: multipart/alternative; boundary="b2"',
    '',
    '--b2',
    'Content-Type: text/plain; charset=utf-8',
    '',
    'It stopped working at 6am.',
    '--b2',
    'Content-Type: text/html; charset=utf-8',
    '',
    '<p>It stopped working at 6am.</p><script>alert(1)</script>',
    '--b2--',
    '--b1',
    'Content-Type: application/pdf; name="invoice.pdf"',
    'Content-Disposition: attachment; filename="invoice.pdf"',
    'Content-Transfer-Encoding: base64',
    '',
    'JVBERi0xLjQKJSVFT0YK',
    '--b1--',
    '',
  ].join('\r\n')
  const p = await parseInboundMime(enc(mime), { from: 'jane@example.com', to: 'support@globproxy.com' })
  assert.equal(normalizeMessageId(`<${p.message_id}>`), 'caf123@mail.example.com')
  assert.equal(p.from.address, 'Jane@Example.com')
  assert.equal(p.subject, 'Re: My proxy stopped [GP-42]')
  assert.equal(p.text.trim(), 'It stopped working at 6am.')
  assert.ok(!p.html.includes('script'), 'raw HTML is not forwarded when a text part exists')
  assert.deepEqual(p.to, ['support@globproxy.com'])
  assert.equal(p.attachments.length, 1)
  assert.equal(p.attachments[0].filename, 'invoice.pdf')
  assert.ok(p.attachments[0].size > 0)
  assert.equal(ticketNoFromSubject(p.subject), 42)
  assert.deepEqual(messageIdsFrom(p.in_reply_to, p.references), ['reply-1@globproxy.com', 'first@mail.example.com'])
  // and it passes the server-side validation unchanged
  assert.equal(validatePayload(p).ok, true)
})

test('an auto-reply carries its marker through parsing', async () => {
  const mime = 'From: a@b.co\r\nTo: support@globproxy.com\r\nSubject: Out of office\r\nAuto-Submitted: auto-replied\r\nPrecedence: bulk\r\nMessage-ID: <o1@b.co>\r\n\r\nI am away.\r\n'
  const p = await parseInboundMime(enc(mime), { from: 'a@b.co', to: 'support@globproxy.com' })
  assert.equal(p.headers['auto-submitted'], 'auto-replied')
  assert.equal(isAutoGenerated(p.headers, 'a@b.co'), true)
})

test('an unreadable message still produces a storable placeholder', () => {
  const p = unreadablePayload({ from: 'jane@example.com', to: 'support@globproxy.com' }, 'Broken', 'm9@x')
  assert.equal(validatePayload(p).ok, true)
  assert.ok(p.text.includes('could not be read'))
})
