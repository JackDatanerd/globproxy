import type { createAdminClient } from '@/lib/supabase/server'
import {
  INBOX_ADDRESSES, SENDER_HOURLY_LIMIT, type InboundPayload,
  normalizeAddress, messageIdsFrom, ticketNoFromSubject, cleanSubject, isAutoGenerated, bodyText,
} from '@/lib/inboxCore'

type Admin = Awaited<ReturnType<typeof createAdminClient>>

export type IngestResult =
  | { status: 'stored'; threadId: string; newThread: boolean; auto: boolean; customerEmail: string; subject: string }
  | { status: 'duplicate' | 'ignored' | 'throttled'; reason: string }

async function sha256Hex(input: string): Promise<string> {
  const d = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(input))
  return Array.from(new Uint8Array(d)).map((b) => b.toString(16).padStart(2, '0')).join('')
}

// Stores one inbound message (see tests/inbox.test.mjs for the rules). Idempotent: Cloudflare may
// deliver the same message twice, and the unique index on message_id turns the second into
// 'duplicate'. Throws only on a database failure, so the caller answers 500 and the Worker can
// bounce the message instead of losing it.
export async function ingestInbound(supabase: Admin, p: InboundPayload): Promise<IngestResult> {
  if (!(INBOX_ADDRESSES as readonly string[]).includes(p.envelope_to)) {
    return { status: 'ignored', reason: 'not an inbox address' }
  }
  const sender = normalizeAddress(p.from?.address) ?? normalizeAddress(p.envelope_from)
  if (!sender) return { status: 'ignored', reason: 'no usable sender address' }
  // Our own outbound mail coming back (a copy, a forward loop) is never a customer message.
  if ((INBOX_ADDRESSES as readonly string[]).includes(sender)) return { status: 'ignored', reason: 'sent from the inbox itself' }

  const text = bodyText(p)
  // Mail without a Message-ID still has to be de-duplicated: derive one from what identifies it.
  const messageId = p.message_id
    ?? `synth-${await sha256Hex([sender, p.date ?? '', p.subject ?? '', text.slice(0, 2000)].join('\n'))}@inbound.invalid`

  const { data: dup, error: dupErr } = await supabase.from('inbox_messages').select('id').eq('message_id', messageId).maybeSingle()
  if (dupErr) throw dupErr
  if (dup) return { status: 'duplicate', reason: 'message_id already stored' }

  // One address cannot bury the inbox.
  const since = new Date(Date.now() - 3_600_000).toISOString()
  const { count: recent, error: recentErr } = await supabase.from('inbox_messages')
    .select('id', { count: 'exact', head: true }).eq('direction', 'in').eq('from_email', sender).gte('created_at', since)
  if (recentErr) throw recentErr
  if ((recent ?? 0) >= SENDER_HOURLY_LIMIT) return { status: 'throttled', reason: `more than ${SENDER_HOURLY_LIMIT} messages from this sender in an hour` }

  const auto = isAutoGenerated(p.headers, sender)

  // ── Which thread? ────────────────────────────────────────────────
  // 1. The message answers one we already hold (In-Reply-To / References) — headers are hard to
  //    forge, so this is trusted whoever sends it.
  // 2. The subject carries our [GP-n] reference — only if the SAME address owns that thread, since
  //    ticket numbers are guessable.
  let threadId: string | null = null
  let customerEmail = sender
  const ids = messageIdsFrom(p.in_reply_to, p.references)
  if (ids.length) {
    const { data: hit, error } = await supabase.from('inbox_messages').select('thread_id').in('message_id', ids).limit(1)
    if (error) throw error
    if (hit?.[0]) threadId = hit[0].thread_id
  }
  if (!threadId) {
    const n = ticketNoFromSubject(p.subject)
    if (n) {
      const { data: t, error } = await supabase.from('inbox_threads').select('id').eq('ticket_no', n).eq('customer_email', sender).maybeSingle()
      if (error) throw error
      if (t) threadId = t.id
    }
  }

  let newThread = false
  let subject = cleanSubject(p.subject)
  if (threadId) {
    const { data: t, error } = await supabase.from('inbox_threads').select('customer_email, subject').eq('id', threadId).maybeSingle()
    if (error) throw error
    if (!t) threadId = null
    else { customerEmail = t.customer_email; subject = t.subject }
  }
  if (!threadId) {
    // Link the sender to an account when the address belongs to one.
    const { data: prof } = await supabase.from('profiles').select('id').eq('email', sender).maybeSingle()
    const { data: created, error } = await supabase.from('inbox_threads').insert({
      subject, customer_email: sender, customer_user_id: prof?.id ?? null,
    }).select('id').single()
    if (error || !created) throw error ?? new Error('thread insert returned no row')
    threadId = created.id
    newThread = true
  }

  if (!threadId) throw new Error('inbox: no thread resolved')
  const tid: string = threadId
  const { error: msgErr } = await supabase.from('inbox_messages').insert({
    thread_id: tid,
    direction: 'in',
    message_id: messageId,
    in_reply_to: p.in_reply_to ? (messageIdsFrom(p.in_reply_to, null)[0] ?? null) : null,
    reference_ids: ids,
    from_email: sender,
    from_name: p.from?.name || null,
    to_emails: p.to,
    cc_emails: p.cc,
    subject: (p.subject ?? '').replace(/[\r\n]+/g, ' ').slice(0, 300) || null,
    text_body: text,
    had_html: !!p.html,
    attachments: p.attachments.map((a) => ({ filename: a.filename, type: a.mime_type, size: a.size })),
    is_auto: auto,
  })
  if (msgErr) {
    // A thread we just made for a message that then failed would sit empty in the list.
    if (newThread) await supabase.from('inbox_threads').delete().eq('id', tid)
    if (msgErr.code === '23505') return { status: 'duplicate', reason: 'message_id already stored (race)' }
    throw msgErr
  }
  return { status: 'stored', threadId: tid, newThread, auto, customerEmail, subject }
}
